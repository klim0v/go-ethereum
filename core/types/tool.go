func calcID(txs []common.Hash, parent common.Hash, subSlot, expires byte, blockTime uint32) (common.Hash, error) {
	hasher := sha3.NewLegacyKeccak256()

	for _, hash := range txs {
		_, err := hasher.Write(hash.Bytes())
		if err != nil {
			return common.Hash{}, err
		}
	}

	if _, err := hasher.Write(parent.Bytes()); err != nil {
		return common.Hash{}, err
	}

	if _, err := hasher.Write([]byte{subSlot}); err != nil {
		return common.Hash{}, err
	}

	if _, err := hasher.Write([]byte{expires}); err != nil {
		return common.Hash{}, err
	}

	blockTimeBytes := make([]byte, 4)
	binary.BigEndian.PutUint32(blockTimeBytes, blockTime)
	if _, err := hasher.Write(blockTimeBytes); err != nil {
		return common.Hash{}, err
	}

	return common.BytesToHash(hasher.Sum(nil)), nil
}
